package postgres

import (
	"context"
	"errors"
	"fmt"
	"net/netip"
	"time"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgxpool"

	"platform/api/internal/session"
)

// SessionRepo implements the session stores on PostgreSQL. Every time comparison uses now() of the
// database, so replicas with skewed clocks agree on expiry, idle and throttling.
type SessionRepo struct {
	pool *pgxpool.Pool
}

// NewSessionRepo returns a SessionRepo over pool.
func NewSessionRepo(pool *pgxpool.Pool) *SessionRepo { return &SessionRepo{pool: pool} }

var (
	_ session.SessionStore    = (*SessionRepo)(nil)
	_ session.AppSessionStore = (*SessionRepo)(nil)
	_ session.LoginCodeStore  = (*SessionRepo)(nil)
	_ session.HostRegistry    = (*SessionRepo)(nil)
)

func seconds(d time.Duration) float64 { return d.Seconds() }

// ipArg maps the zero netip.Addr to SQL NULL.
func ipArg(a netip.Addr) *netip.Addr {
	if !a.IsValid() {
		return nil
	}
	return &a
}

const sessionColumns = `id::text, user_id::text, created_at, last_seen_at, expires_at, ip, coalesce(user_agent, '')`

func scanSession(row pgx.Row) (session.Session, error) {
	var (
		s  session.Session
		ip *netip.Addr
	)
	if err := row.Scan(&s.ID, &s.UserID, &s.CreatedAt, &s.LastSeenAt, &s.ExpiresAt, &ip, &s.UserAgent); err != nil {
		return session.Session{}, err
	}
	if ip != nil {
		s.IP = *ip
	}
	return s, nil
}

// InsertSession implements session.SessionStore. The id is always generated by the database.
func (r *SessionRepo) InsertSession(ctx context.Context, s session.NewSession) (session.Session, error) {
	row := r.pool.QueryRow(ctx, `INSERT INTO sessions (token_hash, user_id, expires_at, ip, user_agent)
		VALUES ($1, $2, now() + make_interval(secs => $3), $4, NULLIF($5, ''))
		RETURNING `+sessionColumns, s.TokenHash, s.UserID, seconds(s.Lifetime), ipArg(s.IP), s.UserAgent)
	out, err := scanSession(row)
	if err != nil {
		return session.Session{}, fmt.Errorf("insert session: %w", err)
	}
	return out, nil
}

// ValidateSession implements session.SessionStore: one statement checks expiry and idle and, when the last
// write is older than the touch window, refreshes last_seen_at. The throttle is re-evaluated by the UPDATE
// itself, so concurrent validations race to a single write.
func (r *SessionRepo) ValidateSession(ctx context.Context, tokenHash []byte, p session.Policy) (session.Session, error) {
	row := r.pool.QueryRow(ctx, `
		WITH cur AS (
			SELECT id, user_id, created_at, last_seen_at, expires_at, ip, user_agent FROM sessions
			WHERE token_hash = $1 AND expires_at > now() AND last_seen_at > now() - make_interval(secs => $2)
		), touched AS (
			UPDATE sessions s SET last_seen_at = now() FROM cur
			WHERE s.id = cur.id AND s.last_seen_at <= now() - make_interval(secs => $3)
			RETURNING s.id
		)
		SELECT cur.id::text, cur.user_id::text, cur.created_at,
		       CASE WHEN EXISTS (SELECT 1 FROM touched) THEN now() ELSE cur.last_seen_at END,
		       cur.expires_at, cur.ip, coalesce(cur.user_agent, '')
		FROM cur`, tokenHash, seconds(p.IdleTimeout), seconds(p.TouchInterval))
	out, err := scanSession(row)
	if errors.Is(err, pgx.ErrNoRows) {
		return session.Session{}, session.ErrInvalidSession
	}
	if err != nil {
		return session.Session{}, fmt.Errorf("validate session: %w", err)
	}
	return out, nil
}

// DeleteSession implements session.SessionStore; app sessions and login codes go by ON DELETE CASCADE.
func (r *SessionRepo) DeleteSession(ctx context.Context, tokenHash []byte) (session.Revoked, error) {
	var rev session.Revoked
	err := r.pool.QueryRow(ctx, `DELETE FROM sessions WHERE token_hash = $1 RETURNING id::text, user_id::text`, tokenHash).
		Scan(&rev.SessionID, &rev.UserID)
	if errors.Is(err, pgx.ErrNoRows) {
		return session.Revoked{}, nil
	}
	if err != nil {
		return session.Revoked{}, fmt.Errorf("delete session: %w", err)
	}
	return rev, nil
}

// DeleteUserSession implements session.SessionStore; scoping by user stops one user closing another's session.
func (r *SessionRepo) DeleteUserSession(ctx context.Context, userID, sessionID string) (bool, error) {
	tag, err := r.pool.Exec(ctx, `DELETE FROM sessions WHERE id = $1 AND user_id = $2`, sessionID, userID)
	if err != nil {
		return false, fmt.Errorf("delete user session: %w", err)
	}
	return tag.RowsAffected() > 0, nil
}

// DeleteUserSessions implements session.SessionStore.
func (r *SessionRepo) DeleteUserSessions(ctx context.Context, userID string) (int64, error) {
	tag, err := r.pool.Exec(ctx, `DELETE FROM sessions WHERE user_id = $1`, userID)
	if err != nil {
		return 0, fmt.Errorf("delete user sessions: %w", err)
	}
	return tag.RowsAffected(), nil
}

// ListActiveSessions implements session.SessionStore.
func (r *SessionRepo) ListActiveSessions(ctx context.Context, userID string, idle time.Duration) ([]session.Session, error) {
	rows, err := r.pool.Query(ctx, `SELECT `+sessionColumns+` FROM sessions
		WHERE user_id = $1 AND expires_at > now() AND last_seen_at > now() - make_interval(secs => $2)
		ORDER BY created_at DESC, id`, userID, seconds(idle))
	if err != nil {
		return nil, fmt.Errorf("list sessions: %w", err)
	}
	defer rows.Close()
	var out []session.Session
	for rows.Next() {
		s, err := scanSession(rows)
		if err != nil {
			return nil, fmt.Errorf("scan session: %w", err)
		}
		out = append(out, s)
	}
	return out, rows.Err()
}

// InsertAppSession implements session.AppSessionStore. The row is only produced when the central session is
// live and the host is a deployment of the app; its expiry is the central session's.
func (r *SessionRepo) InsertAppSession(ctx context.Context, s session.NewAppSession, p session.Policy) (session.AppSession, error) {
	var out session.AppSession
	err := r.pool.QueryRow(ctx, `
		INSERT INTO app_sessions (token_hash, session_id, app_id, host, expires_at)
		SELECT $1, s.id, d.app_id, d.host, s.expires_at
		FROM sessions s JOIN deployments d ON d.host = $4 AND d.app_id = $3
		WHERE s.id = $2 AND s.expires_at > now() AND s.last_seen_at > now() - make_interval(secs => $5)
		RETURNING id::text, session_id::text, (SELECT user_id::text FROM sessions WHERE id = $2), app_id, host, expires_at`,
		s.TokenHash, s.SessionID, s.AppID, s.Host, seconds(p.IdleTimeout),
	).Scan(&out.ID, &out.SessionID, &out.UserID, &out.AppID, &out.Host, &out.ExpiresAt)
	if errors.Is(err, pgx.ErrNoRows) {
		return session.AppSession{}, session.ErrInvalidSession
	}
	if err != nil {
		return session.AppSession{}, fmt.Errorf("insert app session: %w", err)
	}
	return out, nil
}

// ValidateAppSession implements session.AppSessionStore. Besides the app session's own expiry it requires a
// live central session, and refreshes that session's last_seen_at with the same throttling.
func (r *SessionRepo) ValidateAppSession(ctx context.Context, tokenHash []byte, host string, p session.Policy) (session.AppSession, error) {
	var out session.AppSession
	err := r.pool.QueryRow(ctx, `
		WITH cur AS (
			SELECT a.id, a.session_id, s.user_id, a.app_id, a.host, a.expires_at
			FROM app_sessions a JOIN sessions s ON s.id = a.session_id
			WHERE a.token_hash = $1 AND a.host = $2 AND a.expires_at > now()
			  AND s.expires_at > now() AND s.last_seen_at > now() - make_interval(secs => $3)
		), touched AS (
			UPDATE sessions s SET last_seen_at = now() FROM cur
			WHERE s.id = cur.session_id AND s.last_seen_at <= now() - make_interval(secs => $4)
			RETURNING s.id
		)
		SELECT id::text, session_id::text, user_id::text, app_id, host, expires_at FROM cur`,
		tokenHash, host, seconds(p.IdleTimeout), seconds(p.TouchInterval),
	).Scan(&out.ID, &out.SessionID, &out.UserID, &out.AppID, &out.Host, &out.ExpiresAt)
	if errors.Is(err, pgx.ErrNoRows) {
		return session.AppSession{}, session.ErrInvalidSession
	}
	if err != nil {
		return session.AppSession{}, fmt.Errorf("validate app session: %w", err)
	}
	return out, nil
}

// DeleteAppSessions implements session.AppSessionStore.
func (r *SessionRepo) DeleteAppSessions(ctx context.Context, appID string) (int64, error) {
	tag, err := r.pool.Exec(ctx, `DELETE FROM app_sessions WHERE app_id = $1`, appID)
	if err != nil {
		return 0, fmt.Errorf("delete app sessions: %w", err)
	}
	return tag.RowsAffected(), nil
}

// InsertLoginCode implements session.LoginCodeStore.
func (r *SessionRepo) InsertLoginCode(ctx context.Context, c session.NewLoginCode, p session.Policy) error {
	tag, err := r.pool.Exec(ctx, `
		INSERT INTO login_codes (code_hash, session_id, app_id, host, bind_hash, rd, expires_at)
		SELECT $1, s.id, d.app_id, d.host, $5, $6, now() + make_interval(secs => $7)
		FROM sessions s JOIN deployments d ON d.host = $4 AND d.app_id = $3
		WHERE s.id = $2 AND s.expires_at > now() AND s.last_seen_at > now() - make_interval(secs => $8)`,
		c.CodeHash, c.SessionID, c.AppID, c.Host, c.BindHash, c.RD, seconds(c.TTL), seconds(p.IdleTimeout))
	if err != nil {
		return fmt.Errorf("insert login code: %w", err)
	}
	if tag.RowsAffected() != 1 {
		return session.ErrInvalidSession
	}
	return nil
}

// ConsumeLoginCode implements session.LoginCodeStore: a single UPDATE decides, so exactly one caller wins.
func (r *SessionRepo) ConsumeLoginCode(ctx context.Context, codeHash []byte) (session.ConsumedCode, error) {
	var c session.ConsumedCode
	err := r.pool.QueryRow(ctx, `
		UPDATE login_codes SET consumed_at = now()
		WHERE code_hash = $1 AND consumed_at IS NULL AND expires_at > now()
		RETURNING session_id::text, app_id, host, bind_hash, rd`, codeHash,
	).Scan(&c.SessionID, &c.AppID, &c.Host, &c.BindHash, &c.RD)
	if errors.Is(err, pgx.ErrNoRows) {
		return session.ConsumedCode{}, session.ErrInvalidCode
	}
	if err != nil {
		return session.ConsumedCode{}, fmt.Errorf("consume login code: %w", err)
	}
	return c, nil
}

// HostRegistered implements session.HostRegistry.
func (r *SessionRepo) HostRegistered(ctx context.Context, host string) (bool, error) {
	var ok bool
	if err := r.pool.QueryRow(ctx, `SELECT EXISTS (SELECT 1 FROM deployments WHERE host = $1)`, host).Scan(&ok); err != nil {
		return false, fmt.Errorf("check host: %w", err)
	}
	return ok, nil
}
