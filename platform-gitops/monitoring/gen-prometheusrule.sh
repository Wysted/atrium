#!/usr/bin/env bash
# Generates operator/prometheusrule.yaml (PrometheusRule) from rules/portal-platform.rules.yaml, the single source.
# The `groups:` block of the plain file IS spec.groups of the PrometheusRule, so the generation is a re-indent: no YAML
# tool is needed.
#   gen-prometheusrule.sh           # write operator/prometheusrule.yaml
#   gen-prometheusrule.sh --check   # exit 1 if the committed file differs from what would be generated
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
readonly SRC="$HERE/rules/portal-platform.rules.yaml"
readonly OUT="$HERE/operator/prometheusrule.yaml"

render() {
  cat <<'HEADER'
# GENERATED by monitoring/gen-prometheusrule.sh from rules/portal-platform.rules.yaml. Do not edit: change the plain
# file and regenerate (monitoring/test-rules.sh fails when they differ).
apiVersion: monitoring.coreos.com/v1
kind: PrometheusRule
metadata:
  name: portal-platform
  labels:
    app.kubernetes.io/name: portal-platform-alerts
    app.kubernetes.io/part-of: portal-platform
spec:
HEADER
  # Everything from the first `groups:` line, indented under spec. Comment lines before it are the file's own header.
  awk '/^groups:/{p=1} p' "$SRC" | sed 's/^\(.\)/  \1/'
}

case "${1:-}" in
  --check)
    if render | diff -u "$OUT" - >&2; then echo "prometheusrule.yaml is in sync with the plain rules"; else
      echo "operator/prometheusrule.yaml is out of sync: run monitoring/gen-prometheusrule.sh" >&2; exit 1
    fi ;;
  "") render > "$OUT"; echo "wrote ${OUT#"$HERE"/}" ;;
  *) echo "usage: $0 [--check]" >&2; exit 2 ;;
esac
